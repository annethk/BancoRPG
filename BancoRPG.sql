CREATE DATABASE BancoRPG

USE BancoRPG

--	TABELAS

--// Usuário
CREATE TABLE USUARIOS
(
	UsuarioId INT PRIMARY KEY
	,Email VARCHAR(120) NOT NULL
	,Senha VARCHAR(255) NOT NULL
)

--// Classes
CREATE TABLE CLASSES
(
	ClasseId INT PRIMARY KEY
	,Nome VARCHAR(120) NOT NULL
	,Descricao VARCHAR(255) NOT NULL
)

--// Personagens
CREATE TABLE PERSONAGENS
(
	PersonagemId INT PRIMARY KEY 
	,NomePersonagem VARCHAR(120) NOT NULL
	,UsuarioId INT FOREIGN KEY
		REFERENCES USUARIOS(UsuarioId) NOT NULL
	,ClasseId INT FOREIGN KEY
		REFERENCES CLASSES(ClasseId) NOT NULL
)


--// Habilidades
CREATE TABLE HABILIDADES
(
	HabilidadeId INT PRIMARY KEY
	,Nome VARCHAR(120) NOT NULL
)

--// Classes_Habilidades
CREATE TABLE CLASSES_HABILIDADES
(
	ClasseId INT NOT NULL
	,HabilidadeId INT NOT NULL

	PRIMARY KEY(ClasseId, HabilidadeId),

	FOREIGN KEY (ClasseId)
		REFERENCES CLASSES(ClasseId)

	,FOREIGN KEY (HabilidadeId)
		REFERENCES HABILIDADES(HabilidadeId)
)